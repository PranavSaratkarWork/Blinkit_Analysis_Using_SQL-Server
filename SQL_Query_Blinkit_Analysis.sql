/*AVERAGE SALES*/
SELECT AVG(TOTAL_SALES)AS AVG_SALES 
FROM BLINKIT_DATA;

/*AVERAGE SALES WHERE ITEM FAT CONTENT=LOW FAT*/
SELECT AVG(TOTAL_SALES)AS AVG_SALES 
FROM BLINKIT_DATA 
